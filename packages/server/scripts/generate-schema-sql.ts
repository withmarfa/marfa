/**
 * Generate `SCHEMA_SQL` for the requested dialect from the Drizzle migrations.
 *
 * SCHEMA_SQL is the fresh-database bootstrap path that runs every server
 * boot. It must always reflect what `pnpm migrate` would produce starting
 * from `0000`. This script removes the manual three-place sync burden by
 * applying all migrations to a temporary database and dumping the resulting
 * schema into `src/storage/<dialect>/schema-sql.generated.ts`.
 *
 * Usage:
 *   tsx scripts/generate-schema-sql.ts --dialect=sqlite
 *   bash scripts/with-temp-pg.sh tsx scripts/generate-schema-sql.ts --dialect=pg
 *
 * SQLite: applies migrations to libsql `:memory:` and dumps `sqlite_master`.
 *
 * PG: requires DATABASE_URL, set by with-temp-pg.sh on every path including
 *     CI. Applies all migrations, then invokes pg_dump — preferring
 *     `docker exec` into the container named in PG_CONTAINER_NAME (version-
 *     matched dump) and falling back to the host pg_dump binary, which no
 *     automated path reaches now that the wrapper always names a container. Grants are captured separately from information_schema
 *     because pg_dump --no-privileges strips them.
 *
 * The FTS5 virtual table in sqlite/connection.ts is NOT in scope — Drizzle
 * Kit cannot express FTS5, so it never appears in any migration. The
 * connection.ts file applies SCHEMA_SQL first, then the FTS5 block.
 */

import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createClient } from "@libsql/client";
import postgres from "postgres";
import {
  runPgMigrations,
  runSqliteMigrations,
} from "../src/storage/migrate.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SERVER_ROOT = join(__dirname, "..");

const GENERATED_HEADER = `// Code generated by scripts/generate-schema-sql.ts; DO NOT EDIT.
//
// SCHEMA_SQL is the fresh-database bootstrap path. It runs every server
// boot via createConnection() and must stay in sync with the Drizzle
// migrations under drizzle/<dialect>/. To refresh, run:
//   pnpm --filter @withmarfa/server schema-sql:generate
// (or implicitly via migrate:<dialect>:generate when a new migration lands).
//
// Hand-edits to this file will be overwritten on the next regen and will
// fail the schema-sql-freshness CI check.
`;

type Dialect = "pg" | "sqlite";

function parseDialect(): Dialect {
  const arg = process.argv.find((a) => a.startsWith("--dialect="));
  if (!arg) {
    throw new Error("--dialect=pg|sqlite is required");
  }
  const value = arg.split("=")[1] ?? "";
  if (value !== "pg" && value !== "sqlite") {
    throw new Error(`unknown dialect: ${value}`);
  }
  return value;
}

