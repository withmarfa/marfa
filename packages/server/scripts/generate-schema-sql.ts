/**
 * Generate `SCHEMA_SQL` from the Drizzle migrations.
 *
 * SCHEMA_SQL is the fresh-database bootstrap path that runs every server
 * boot. It must always reflect what `pnpm migrate` would produce starting
 * from `0000`. This script removes the manual sync burden by applying all
 * migrations to a temporary database and dumping the resulting schema into
 * `src/storage/sqlite/schema-sql.generated.ts`.
 *
 * Usage:
 *   tsx scripts/generate-schema-sql.ts
 *
 * Applies migrations to libsql `:memory:` and dumps `sqlite_master`.
 *
 * The FTS5 virtual table in sqlite/connection.ts is NOT in scope — Drizzle
 * Kit cannot express FTS5, so it never appears in any migration. The
 * connection.ts file applies SCHEMA_SQL first, then the FTS5 block.
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createClient } from "@libsql/client";
import { runSqliteMigrations } from "../src/storage/migrate.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SERVER_ROOT = join(__dirname, "..");

const GENERATED_HEADER = `// Code generated by scripts/generate-schema-sql.ts; DO NOT EDIT.
//
// SCHEMA_SQL is the fresh-database bootstrap path. It runs every server
// boot via createConnection() and must stay in sync with the Drizzle
// migrations under drizzle/sqlite/. To refresh, run:
//   pnpm --filter @withmarfa/server schema-sql:generate
//
// Hand-edits to this file will be overwritten on the next regen and will
// fail the schema-sql parity test.
`;

// ---------------------------------------------------------------------------
// SQLite
// ---------------------------------------------------------------------------

/**
 * Apply migrations to an in-memory libsql DB and dump the resulting schema.
 *
 * Order: tables first, in `rootpage` order, then indexes grouped by table.
 *
 * `rootpage` is the page the table's b-tree starts on, not a creation counter.
 * SQLite allocates it when the table is created and reallocates it when the
 * table is created again, so a table a later migration rebuilds sorts by that
 * rebuild rather than by when it first appeared: `api_keys` is the standing
 * example, since SQLite cannot add a CHECK in place and every constraint it
 * gains arrives as a drop and a recreate. Freed pages go on the freelist and
 * are handed out again, and VACUUM renumbers the file wholesale, so the value
 * carries no history at all.
 *
 * What it does give is the one property this needs: applying one migration
 * chain to one empty database is deterministic, so the dump comes out in the
 * same order every run and the freshness check compares like with like.
 * Nothing downstream reads the order as meaning anything. Indexes are emitted
 * in a second pass so they always follow their table, and the equality test
 * sorts both sides by name before comparing.
 */
async function dumpSqlite(): Promise<string> {
  // Use a shared-cache in-memory URL so the migrator and dump connection see
  // the same in-memory DB across libsql client logical connections. Matches
  // the URL shape `toLibsqlUrl(":memory:")` produces in sqlite/connection.ts.
  const url = "file::memory:?cache=shared";
  await runSqliteMigrations(url);

  const client = createClient({ url });
  try {
    const tables = await client.execute({
      sql: `
        SELECT name, sql
        FROM sqlite_master
        WHERE type = 'table'
          AND name NOT LIKE 'sqlite_%'
          AND name != '__drizzle_migrations'
        ORDER BY rootpage
      `,
      args: [],
    });
    const indexes = await client.execute({
      sql: `
        SELECT name, sql, tbl_name
        FROM sqlite_master
        WHERE type = 'index'
          AND sql IS NOT NULL
          AND tbl_name NOT LIKE 'sqlite_%'
          AND tbl_name != '__drizzle_migrations'
        ORDER BY tbl_name, name
      `,
      args: [],
    });

    const parts: string[] = [];
    for (const row of tables.rows) {
      parts.push(toIdempotentSqlite(row.sql as string) + ";");
    }
    for (const row of indexes.rows) {
      parts.push(toIdempotentSqlite(row.sql as string) + ";");
    }
    return parts.join("\n\n") + "\n";
  } finally {
    client.close();
  }
}

/**
 * Rewrite a SQLite DDL statement for re-run safety:
 *   CREATE TABLE          -> CREATE TABLE IF NOT EXISTS
 *   CREATE INDEX          -> CREATE INDEX IF NOT EXISTS
 *   CREATE UNIQUE INDEX   -> CREATE UNIQUE INDEX IF NOT EXISTS
 *
 * sqlite_master returns the original DDL as written in the migration, which
 * for Drizzle-generated migrations never includes IF NOT EXISTS — those
 * guards are added here so SCHEMA_SQL is idempotent across server boots.
 */
function toIdempotentSqlite(ddl: string): string {
  return ddl
    .replace(/^CREATE TABLE(?! IF NOT EXISTS)\b/i, "CREATE TABLE IF NOT EXISTS")
    .replace(
      /^CREATE UNIQUE INDEX(?! IF NOT EXISTS)\b/i,
      "CREATE UNIQUE INDEX IF NOT EXISTS",
    )
    .replace(
      /^CREATE INDEX(?! IF NOT EXISTS)\b/i,
      "CREATE INDEX IF NOT EXISTS",
    );
}

// ---------------------------------------------------------------------------
// Output
// ---------------------------------------------------------------------------

function writeGenerated(sql: string): string {
  const outPath = join(
    SERVER_ROOT,
    "src",
    "storage",
    "sqlite",
    "schema-sql.generated.ts",
  );
  mkdirSync(dirname(outPath), { recursive: true });
  // Escape for embedding into a template literal.
  const escaped = sql
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
  const body = `${GENERATED_HEADER}
export const SCHEMA_SQL = \`
${escaped}\`;
`;
  writeFileSync(outPath, body, "utf-8");
  return outPath;
}

async function main(): Promise<void> {
  process.stderr.write("Generating SCHEMA_SQL...\n");
  const sql = await dumpSqlite();
  const outPath = writeGenerated(sql);
  process.stderr.write(`  → ${outPath}\n`);
}

main().then(
  () => process.exit(0),
  (err: unknown) => {
    process.stderr.write(`generate-schema-sql failed: ${String(err)}\n`);
    process.exit(1);
  },
);
