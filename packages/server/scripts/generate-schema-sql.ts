// Output
// ---------------------------------------------------------------------------

function writeGenerated(dialect: Dialect, sql: string): string {
  const outPath = join(
    SERVER_ROOT,
    "src",
    "storage",
    dialect,
    "schema-sql.generated.ts",
  );
  mkdirSync(dirname(outPath), { recursive: true });
  // Escape for embedding into a template literal.
  const escaped = sql
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$\{/g, "\\${");
  const body = `${GENERATED_HEADER}
export const SCHEMA_SQL = \`
${escaped}\`;
`;
  writeFileSync(outPath, body, "utf-8");
  return outPath;
}

async function main(): Promise<void> {
  const dialect = parseDialect();
  process.stderr.write(`Generating ${dialect} SCHEMA_SQL...\n`);
  const sql = dialect === "sqlite" ? await dumpSqlite() : await dumpPg();
  const outPath = writeGenerated(dialect, sql);
  process.stderr.write(`  → ${outPath}\n`);
}

main().then(
  () => process.exit(0),
  (err: unknown) => {
    process.stderr.write(`generate-schema-sql failed: ${String(err)}\n`);
    process.exit(1);
  },
);
