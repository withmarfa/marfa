/**
 * Builds the stylesheet and script every server-rendered page loads, and
 * writes them into `src/pages/assets.generated.ts` as strings with their
 * content hashes.
 *
 * The file is not committed. `pnpm build`, `pnpm dev`, the tests' global
 * setup and the scripts that boot the server from source each write it from
 * the sources before anything reads it, so all of them serve the same bytes
 * and none can serve stale ones.
 *
 *   tsx scripts/build-page-assets.ts          build once
 *   tsx scripts/build-page-assets.ts --watch  build again when a source changes
 */
import { createHash } from "node:crypto";
import {
  existsSync,
  readFileSync,
  renameSync,
  watch,
  writeFileSync,
} from "node:fs";
import { join } from "node:path";
import { build, transform } from "esbuild";

const PAGES = join(import.meta.dirname, "..", "src", "pages");
const GENERATED = join(PAGES, "assets.generated.ts");

export interface PageAssets {
  css: string;
  js: string;
}

const sha1 = (text: string): string =>
  createHash("sha1").update(text).digest("hex");

/** The stylesheet: the tokens, then the parts, minified into one file. */
async function buildCss(): Promise<string> {
  const source = ["tokens.css", "parts.css"]
    .map((name) => readFileSync(join(PAGES, "styles", name), "utf8"))
    .join("\n");
  const result = await transform(source, { loader: "css", minify: true });
  return result.code;
}

/** The script: the browser modules bundled into one file with no imports left. */
async function buildJs(): Promise<string> {
  const result = await build({
    entryPoints: [join(PAGES, "client", "index.ts")],
    tsconfig: join(PAGES, "client", "tsconfig.json"),
    bundle: true,
    write: false,
    outfile: "pages.js",
    format: "iife",
    platform: "browser",
    target: "es2022",
    minify: true,
    legalComments: "none",
    logLevel: "silent",
  });
  const [file] = result.outputFiles;
  if (!file) throw new Error("esbuild produced no script");
  return file.text;
}

export async function buildPageAssets(): Promise<PageAssets> {
  const [css, js] = await Promise.all([buildCss(), buildJs()]);
  return { css, js };
}

/** The text of `assets.generated.ts` for these assets. */
export function renderGeneratedModule(assets: PageAssets): string {
  return [
    "// Generated by scripts/build-page-assets.ts from src/pages/styles and src/pages/client. Do not edit.",
    `export const PAGE_CSS = ${JSON.stringify(assets.css)};`,
    `export const PAGE_CSS_VERSION = ${JSON.stringify(sha1(assets.css))};`,
    `export const PAGE_JS = ${JSON.stringify(assets.js)};`,
    `export const PAGE_JS_VERSION = ${JSON.stringify(sha1(assets.js))};`,
    "",
  ].join("\n");
}

/**
 * Writes `assets.generated.ts` from the sources and says whether the file
 * changed. A file that already holds the same bytes is left alone, so a
 * rebuild does not move its modification time. The write goes to a file of
 * its own first and is renamed over the target, so a process that starts
 * while another writes reads the old file or the new one, never half of it.
 */
export async function writePageAssets(target = GENERATED): Promise<boolean> {
  const next = renderGeneratedModule(await buildPageAssets());
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current === next) return false;
  const staging = `${target}.${String(process.pid)}.tmp`;
  writeFileSync(staging, next);
  renameSync(staging, target);
  return true;
}

async function main(): Promise<void> {
  const changed = await writePageAssets();
  console.log(
    changed ? "Page assets written." : "Page assets already up to date.",
  );
  if (!process.argv.includes("--watch")) return;

  let timer: NodeJS.Timeout | undefined;
  watch(PAGES, { recursive: true }, (_event, name) => {
    if (
      name === null ||
      name.includes("generated") ||
      name.endsWith(".test.ts")
    )
      return;
    clearTimeout(timer);
    timer = setTimeout(() => {
      writePageAssets().then(
        (rewritten) => {
          if (rewritten) console.log("Page assets rebuilt.");
        },
        (error: unknown) => {
          console.error(error);
        },
      );
    }, 100);
  });
}

if (process.argv[1] === import.meta.filename) {
  main().catch((error: unknown) => {
    console.error(error);
    process.exitCode = 1;
  });
}
